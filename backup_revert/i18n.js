  t(key) {
    const dict = this.translations[this.currentLang] || this.translations['gu'];
    return (dict && dict[key] !== undefined)
      ? dict[key]
      : (this.translations['en'] && this.translations['en'][key] !== undefined ? this.translations['en'][key] : key);
  },

  setLang(lang) {
    if (this.translations[lang]) {
      this.currentLang = lang;
      this.updateDOM();
      localStorage.setItem('hisab_lang', lang);
      
      // Trigger custom event so any active component can re-render if needed
      window.dispatchEvent(new CustomEvent('hisab-lang-changed', { detail: { lang } }));
    }
  },

